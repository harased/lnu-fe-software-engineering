# Імпортуємо необхідні модулі з фреймворку Flask:
# Flask — основний клас для створення веб-сервера
# render_template — для відображення HTML-шаблонів із папки templates
# request — для отримання даних, надісланих користувачем (наприклад, з HTML-форм)
# redirect — для перенаправлення користувача на іншу сторінку
# url_for — для динамічної генерації URL-адрес на основі назв функцій
from flask import Flask, render_template, request, redirect, url_for

# Створюємо екземпляр додатку Flask.
# __name__ вказує Flask, де шукати ресурси (шаблони, статичні файли)
app = Flask(__name__)

# Тимчасова "база даних" у пам'яті — список із початковими завданнями
tasks = ["Виконати LAB-07", "Почистити зуби", "Лягти спати"]


# Маршрут для головної сторінки (URL: '/')
@app.route('/')
def home():
    # Повертає простий текстовий привітний рядок при переході на корінь сайту
    return "Вітаю у веб-сервісі на Flask!"


# Маршрут для перегляду списку завдань (URL: '/tasks')
@app.route('/tasks')
def task_list():
    # Рендерить HTML-шаблон 'tasks.html' і передає в нього список завдань через змінну tasks
    return render_template('tasks.html', tasks=tasks)


# Маршрут для додавання нового завдання (URL: '/add').
# Підтримує два HTTP-методи: GET (для відображення форми) та POST (для відправки даних з форми)
@app.route('/add', methods=['GET', 'POST'])
def add_task():
    # Перевіряємо, чи запит надіслано методом POST (тобто користувач натиснув кнопку "Додати")
    if request.method == 'POST':
        # Отримуємо значення з поля введення з name="task"
        new_task = request.form['task']

        # Перевіряємо, чи введений текст не є порожнім
        if new_task:
            # Додаємо нове завдання до нашого списку tasks
            tasks.append(new_task)
        else:
            # Якщо поле порожнє, повертаємо повідомлення про помилку та HTTP-код status 400 (Bad Request)
            return "Завдання не може бути порожнім", 400

        # Після успішного додавання перенаправляємо користувача назад на сторінку списку завдань
        return redirect(url_for('task_list'))

    # Якщо метод GET (користувач просто відкрив сторінку /add), відображаємо форму додавання
    return render_template('add_task.html')


# === НОВА ФУНКЦІЯ: Видалення завдання за його індексом (URL: '/delete/<task_id>') ===
# Приймає параметр task_id як ціле число (int) та працює за методом POST
@app.route('/delete/<int:task_id>', methods=['POST'])
def delete_task(task_id):
    # Перевіряємо, чи існує завдання з таким індексом у нашому списку
    if 0 <= task_id < len(tasks):
        # Видаляємо елемент із списку за його індексом
        tasks.pop(task_id)

    # Після видалення перенаправляємо користувача назад до оновленого списку завдань
    return redirect(url_for('task_list'))


# Точка входу в програму: перевіряємо, чи файл запускається напряму, а не імпортується
if __name__ == '__main__':
    # Запускаємо локальний веб-сервер Flask у режимі налагодження (debug=True дозволяє бачити помилки та автооновлювати сервер)
    app.run(debug=True)